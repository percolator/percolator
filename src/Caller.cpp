Caller::Caller()
    : readStdIn_(false),
      inputFN_(""),
      inputFNs_(),
      protEstimatorDecoyPrefix_("auto"),
      tabOutputFN_(""),
      weightOutputFN_(""),
      psmResultFN_(""),
      peptideResultFN_(""),
      proteinResultFN_(""),
      decoyPsmResultFN_(""),
      decoyPeptideResultFN_(""),
      decoyProteinResultFN_(""),
      reportUniquePeptides_(true),
      targetDecoyCompetition_(false),
      useMixMax_(false),
      inputSearchType_("auto"),
      selectionFdr_(0.01),
      initialSelectionFdr_(0.01),
      testFdr_(0.01),
      numIterations_(10),
      maxPSMs_(0u),
      nestedXvalBins_(1u),
      numThreads_(3u),
      selectedCpos_(0.0),
      selectedCneg_(0.0),
      reportEachIteration_(false),
      quickValidation_(false),
      trainBestPositive_(false),
      useResetAlgorithm_(false),
      useCompositionMatch_(false),
      useIrlsPep_(false),
      useInterpolatingPep_(true),
      usePavaPep_(false),
      useTdcPep_(false) {
  // A process can run Percolator more than once (Crux, the unit tests).
  // The settings below are process-wide and changed by the options and by
  // the steps of a run, so they are set back to their initial values here,
  // and every run gives the same results as in a new process.
  PseudoRandom::setSeed(1u);
  PosteriorEstimator::resetToDefaults();
  ProteinProbEstimator::setCalcProteinLevelProb(false);
  PSMDescription::setProteinNameSeparator("\t");
  PSMDescription::resetSpectrumFileNames();
  DataSet::resetFeatureNames();
  DataSet::resetWarnings();
}

Caller::~Caller() {}

string Caller::extendedGreeter() {
  ostringstream oss;
  char* host = getenv("HOSTNAME");
  oss << greeter();
  oss << "Issued command:" << endl << call_ << endl;
  oss << "Started " << timer.getStartTimeStr() << endl;
  oss.seekp(-1, ios_base::cur);
  if (host)
    oss << " on " << host << endl;
  oss << "Hyperparameters: selectionFdr=" << selectionFdr_
      << ", Cpos=" << selectedCpos_ << ", Cneg=" << selectedCneg_
      << ", maxNiter=" << numIterations_ << endl;
  return oss.str();
}

string Caller::greeter() {
  ostringstream oss;
  oss << "Percolator version " << VERSION << ", ";
  oss << "Build Date " << __DATE__ << " " << __TIME__ << endl;
  oss << "Copyright (c) 2006-9 University of Washington. All rights reserved.\n"
      << "Written by Lukas Käll (lukall@u.washington.edu) in the\n"
      << "Department of Genome Sciences at the University of Washington.\n";
  return oss.str();
}

